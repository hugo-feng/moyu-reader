export function buildDemoBookText(): string {
  const head = [
    `《${DEMO_BOOK_TITLE}》`,
    `作者：${DEMO_BOOK_AUTHOR}`,
    '简介：一个少年从雪夜山道出发，走过剑冢与听雨楼，最终把名字留在江湖上的故事。本示例文本由墨阅阅读器项目原创，仅用于功能验证。',
    '',
  ].join('\n')

  const chapters = DEMO_CHAPTERS.map((c) => `${c.title}\n${c.body}`).join('\n\n')
  return `${head}\n${chapters}\n`
}

