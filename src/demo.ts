/**
 * 演示书内容。
 *
 * 用途：让验证器一打开就有真实可读的长篇内容，从而能真正验证分章、分页、
 * 翻页、搜索、统计这些功能，而不是面对一个空书架。内容为本项目原创，
 * 刻意写成多样化的章节标题格式，用来压测分章算法。
 */

export const DEMO_BOOK_TITLE = '剑影长歌'
export const DEMO_BOOK_AUTHOR = '墨阅示例'

/** 生成一段有辨识度的正文，避免重复文本让搜索测试失去意义。 */
function para(seed: string, n: number): string {
  const pool = [
    '山道上积雪未消，脚踩下去发出细碎的声响。',
    '他握紧了剑柄，指节因用力而泛白。',
    '远处传来一声悠长的钟鸣，惊起满林寒鸦。',
    '风从峡谷深处卷上来，带着铁锈与松脂的气味。',
    '她没有回头，只把斗篷的兜帽压低了些。',
    '灯火在窗纸上晃出一个模糊的人影。',
    '茶已经凉透，杯底沉着一层暗褐色的叶屑。',
    '马蹄声由远及近，又在门前骤然停住。',
    '刀锋映着月光，像一线流动的水银。',
    '他忽然笑了一声，那笑意却没有到达眼底。',
    '老人把一卷泛黄的帛书推到桌案中央。',
    '雨点开始敲打屋檐，先是零星，继而连成一片。',
    '她袖中的短匕已经滑出半寸。',
    '少年抬起头，眼里的惊惶已经褪尽。',
    '石门在身后缓缓合拢，隔绝了最后一线天光。',
  ]
  const out: string[] = []
  for (let i = 0; i < n; i++) {
    out.push(pool[(i * 7 + seed.length) % pool.length])
    if (i % 3 === 2) {
      out.push(`第 ${i + 1} 次交手之后，${seed}这个名字开始在江湖上被人低声提起，带着几分忌惮，也带着几分说不清的期待。`)
    }
    if (i % 5 === 4) {
      out.push('　')
    }
  }
  return out.join('')
}

/**
 * 一个刻意写长的章节。
 *
 * 存在的理由：其余演示章都只有一两百字，在手机尺寸下一章恰好一页 ——
 * 于是"分页是否正确""翻到次页会不会丢字""次页起该不该印书眉"这些
 * 真正要命的路径，在验证器里根本走不到。这一章用来把那些路径压出来。
 */
function longChapter(): string {
  const parts = [
    '雨是从傍晚开始下的。\n起初只是疏落的几点，打在客栈的青瓦上，声音清而脆；到了二更，雨势忽然紧了，连成一片，檐下挂起一道不断线的水帘。\n少年坐在窗边，把那柄剑搁在膝上，一遍一遍地擦。剑身上并没有锈，他也不是在擦锈。',
    '楼下的说书人还在讲那桩旧事。讲的是十年前剑冢一役，七家掌门围攻一人，最后只有三家活着走出山谷。说书人把它讲成了一段快意恩仇，听众拍着桌子叫好，铜钱落在盘子里叮当作响。\n少年没有拍桌子。他知道那一段的后半截，说书人从来没讲过。',
    '三更时分，隔壁房间传来极轻的一声响。\n那不是风吹窗纸的响，也不是老鼠碰倒碗盏的响。那是一个人从床上起身，脚尖落地，又把重心缓缓移回去的响——这个人不希望被听见。\n少年没有说话，只是把剑从膝上拿起来，横放在身前。',
    '又过了半炷香的工夫，脚步声停在门外。\n敲门声很轻，三下，间隔一样长。\n"进来。"少年说。\n门开了。来人一身湿透的蓑衣，斗笠压得很低，只露出半张下巴。他没有立刻进门，先在门槛外站了一会儿，像是在确认屋里只有一个人。',
    '来人这才跨进来，反手把门合上，取下斗笠。\n那是一张少年的脸，比他还小几岁，眉眼很干净，右手虎口上却有一道新鲜的伤口，血已经凝住了，边缘发黑。\n"你是雪夜山道上走下来的那个人。"来人说，"我等了你三个月。"',
    '少年没有答话。\n"我姓沈。"来人从怀里取出一枚令牌，放在桌上，"剑宗，外门执事。这枚令牌你可以验，也可以不验——但你师父的名字，你应该认得。"\n令牌是乌木的，边缘磨得发亮，中间刻着一个"沈"字。少年的手指在剑柄上收紧了一寸。',
    '窗外又是一道闪电，把整间屋子照得雪白。\n雷声跟上来的时候，沈姓少年已经坐下了。他的动作很稳，稳得不像一个身上带着伤的人。\n"你师父不是病死的。"他说。',
    '这句话之后，屋子里安静了很久。\n少年听见自己的心跳，一下，一下，敲在肋骨上。他早就在等这句话，等了三年——从他把师父的遗物一件件收进箱子的那天起，他就在等有人来跟他说这句话。可是真等到了，他发现自己并没有想象中那样想要一个答案。',
    '"三年前的霜降，"沈姓少年继续说，"你师父一个人在剑冢，挡住了七个人。他退到第三道石门的时候，还剩着一口气。那口气撑到天亮。"\n"你怎么知道。"\n"因为我是那七个人里，唯一活下来的。"',
    '雨声忽然大了一瞬，又落回去。\n少年把剑慢慢推出去半寸，又停住。他看见对面那人的手一直放在桌面上，掌心朝下，没有去碰腰间的刀。\n"那你来做什么。"\n"我来告诉你，他那一夜到底在护什么。"',
    '沈姓少年从贴身的夹层里取出一卷帛书，很旧了，边角被水浸过，又被火燎过。他把帛书放在桌上，推到两人中间，却没有松手。\n"这是你师父托我带的。他说，若是他没能走出来，就把这个交给他那个从雪夜山道上下来的徒弟。"\n"他凭什么认定我会来。"\n"因为他把这条路，只告诉过你一个人。"',
    '少年终于伸出手，按在那卷帛书上。\n帛书是凉的，凉得不像在人的怀里揣了三年的东西。\n他没有立刻抽开。\n"你为什么不早来。"他问。\n"因为有两拨人在找我。"沈姓少年说，"前两年我在山里，第三年我在牢里。今天走出牢门的第六个时辰，我坐在这里。"',
    '远处传来一声鸡鸣，很轻，隔着雨声几乎听不见。\n少年把帛书收进怀里，站起身来。他知道从这一刻起，雪夜山道那一夜才算真正结束，而另一个更长的夜，才刚刚开始。\n"你还有别的话要说吗。"\n"有一句。"沈姓少年抬起头，"那七个人里，活下来的不止我一个——只是另外那几个，不叫这个名字了。"',
    '天亮的时候，雨停了。\n客栈的院子里积着水，倒映着灰白的天。少年站在廊下，看了一会儿水里的自己，然后转身出门，没有回头。',
  ]
  return parts.join('')
}

