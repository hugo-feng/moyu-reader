/**
 * 形变图标的路径数据（两端共用）。
 *
 * ## 为什么只保留这三对
 *
 * morphicons 的算法是「子路径按弧长重采样 → 强制配对 → 在点列之间插值」。
 * 当两个图标的**结构与子路径数量接近**时，中间帧是漂亮的连续过渡；
 * 差距大时（例如 3 根柱子的统计图 ↔ 6 个子路径的笔记本），
 * 配对会强行把不相干的笔画连起来，中间帧变成一团纠缠的线。
 *
 * 这是配对策略的固有结果，调参数救不回来。实测（tests/probe-morph-pairs.mjs）：
 *   ✓ 月亮 → 太阳        圆形基底，过渡自然
 *   ✓ 放大镜 → 关闭      两条简笔，干净
 *   ✓ 书签 → 已收藏      同一外形 + 一个对勾长出来
 *   ✗ 书架 ↔ 统计 ↔ 笔记 ↔ 设置   中间帧乱成一团（因此**底部标签栏不用形变**）
 *   ✗ 播放 → 暂停        退化成两个「D」形
 *
 * 所以这里只留三对真正好看的。底部标签栏回到常规的淡入淡出 ——
 * 一个每次点都要看到的难看中间帧，比没有动效糟得多。
 *
 * ## 数据约定
 *
 * - 只允许 path / line / circle / ellipse / rect / polyline / polygon，坐标必须是字面量，
 *   不能有 `<g>` 或 transform。
 * - 全部取自 Lucide 的 24×24 网格，因此跨界配对天然成立。
 * - circle / rect 已手工展开成等价的 arc / 贝塞尔 path：少一种图元，
 *   Android 端的解析器就少一类要处理的形状，两端更容易保持一致。
 * - `resampleIcon` 的输入是**单个 d 字符串**（内部按 M 拆子路径），
 *   或 IconNode；**不是**「d 字符串数组」—— 传数组会报 `unsupported tag <M>`。
 *
 * ## 唯一真相来源
 *
 * 这份数据是两端共用的。Kotlin 侧的 `MorphIcons.kt` 逐条照抄，
 * 改任何一端都必须同步另一端 —— 否则「验证器里好看、手机上不对」。
 */

